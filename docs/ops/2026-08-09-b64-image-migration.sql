-- לפני: SECURITY DEFINER (עוקף RLS) · anon *וגם* PUBLIC יכלו להריץ · אפס
-- בדיקת auth.uid(). היא קיבלה p_user_id והאמינה לו. מפתח anon מתפרסם בקוד
-- ה-JavaScript הציבורי מתוקף התכנון ⇒ כל אחד יכול היה לכתוב להיסטוריה של כל
-- משתמש, וכל קריאה כזו גם הוסיפה שורה ל-answer_history דרך הטריגר.
--
-- שים לב: המיגרציה המקורית (20260323000001) נתנה הרשאה ל-authenticated בלבד.
-- ההרשאות ל-anon ול-PUBLIC נוספו מאוחר יותר, מחוץ למיגרציות — זו הייתה הפרצה.
--
-- החלטת עידן (9.8.2026): אי-התאמה **זורקת שגיאה**, לא נכשלת בשקט —
-- כדי שבאג אמיתי יתגלה מיד במקום לאבד תשובות בלי שאף אחד ידע.
-- שני הקוראים (AppContext.tsx:500, :653) כבר מטפלים בשגיאה ומציגים toast בעברית.

-- הגוף עודכן: נוסף רק הבלוק הזה בתחילת הפונקציה, שאר הלוגיקה זהה לחלוטין.
