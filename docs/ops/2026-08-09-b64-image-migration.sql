REVOKE EXECUTE ON FUNCTION public.increment_user_answer(uuid, text, boolean, text) FROM anon;
REVOKE EXECUTE ON FUNCTION public.increment_user_answer(uuid, text, boolean, text) FROM PUBLIC;
-- הרשאות אחרי: postgres | authenticated | service_role   (בלי anon, בלי PUBLIC)

-- בדיקה שרצה לפני ה-REVOKE, בתוך טרנזקציה שבוטלה (RAISE בסוף → rollback):
--   משתמש אמיתי עם JWT תקין ....... SUCCEEDED  ✔
--   p_user_id מזויף ............... BLOCKED    ✔
